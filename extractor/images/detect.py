from __future__ import annotations

import json
import re
from dataclasses import dataclass
from fnmatch import fnmatchcase

from sqlalchemy import Engine, inspect
from sqlalchemy import types as T

from ..config import ImagesConfig
from ..dump import q

_ATTR = re.compile(r"""(?:src|data-src|data-original|href|poster)\s*=\s*(["'])(.*?)\1""", re.I | re.S)
_SRCSET = re.compile(r"""srcset\s*=\s*(["'])(.*?)\1""", re.I | re.S)
_CSSURL = re.compile(r"""url\(\s*["']?([^"')]+)["']?\s*\)""", re.I)
_PHP_SERIALIZED = re.compile(r"^(?:a|O):\d+:[{\"]")
_PHP_STRING = re.compile(r's:\d+:"(.*?)";', re.S)


def _strings(obj):
    if isinstance(obj, str):
        yield obj
    elif isinstance(obj, dict):
        for v in obj.values():
            yield from _strings(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _strings(v)


class Detector:
    """Finds image references (URLs, paths or bare filenames) inside a cell value."""

    def __init__(self, extensions: list[str]):
        ext = "(?:" + "|".join(re.escape(e) for e in extensions) + ")"
        self.bare = re.compile(rf"""^[^\s<>"'|;]+\.{ext}(?:\?[^\s<>"']*)?$""", re.I)
        self.absolute = re.compile(
            rf"""https?://[^\s"'<>()\\,]+?\.{ext}(?:\?[^\s"'<>()\\]*)?(?=[\s"'<>()\\,;!]|\.(?:\s|$)|$)""", re.I
        )

    def extract(self, value) -> list[str]:
        if not isinstance(value, str) or len(value) > 2_000_000:
            return []
        out: list[str] = []
        self._extract(value.strip(), out, 0)
        return list(dict.fromkeys(out))

    def _extract(self, s: str, out: list[str], depth: int) -> None:
        if not s or depth > 3 or s.lower().startswith("data:"):
            return
        if self.bare.match(s):
            out.append(s)
            return
        if s[0] in "{[":
            try:
                obj = json.loads(s)
            except ValueError:
                obj = None
            if obj is not None:
                for text in _strings(obj):
                    self._extract(text.strip(), out, depth + 1)
                return
        if _PHP_SERIALIZED.match(s):
            for m in _PHP_STRING.finditer(s):
                self._extract(m.group(1).strip(), out, depth + 1)
            return
        for m in _ATTR.finditer(s):
            if self.bare.match(m.group(2).strip()):
                out.append(m.group(2).strip())
        for m in _SRCSET.finditer(s):
            for part in m.group(2).split(","):
                url = part.strip().split(" ")[0]
                if self.bare.match(url):
                    out.append(url)
        for m in _CSSURL.finditer(s):
            if self.bare.match(m.group(1).strip()):
                out.append(m.group(1).strip())
        out.extend(m.group(0) for m in self.absolute.finditer(s))


def matches(patterns: list[str], table: str, column: str) -> bool:
    target = f"{table}.{column}".lower()
    return any(fnmatchcase(target, p.lower()) for p in patterns)


@dataclass
class ColumnReport:
    table: str
    column: str
    forced: bool
    sampled: int
    hits: int
    selected: bool
    refs: int = 0
    distinct: int = 0

    @property
    def ratio(self) -> float:
        return self.hits / self.sampled if self.sampled else 0.0


def select_columns(dest: Engine, cfg: ImagesConfig, det: Detector) -> list[ColumnReport]:
    """Decide which text columns hold image references (auto-detect + config overrides)."""
    insp = inspect(dest)
    reports: list[ColumnReport] = []
    for table in sorted(insp.get_table_names()):
        if table.startswith("_"):
            continue
        cols = insp.get_columns(table)
        names = {c["name"] for c in cols}
        for col in cols:
            name = col["name"]
            if not isinstance(col["type"], T.String):
                continue
            if name.endswith("_local") and name[: -len("_local")] in names:
                continue  # column generated by `link`
            if matches(cfg.exclude_columns, table, name):
                continue
            forced = matches(cfg.include_columns, table, name)
            with dest.connect() as c:
                values = [
                    r[0]
                    for r in c.exec_driver_sql(
                        f"SELECT {q(name)} FROM {q(table)} WHERE {q(name)} IS NOT NULL AND {q(name)} != '' "
                        f"LIMIT {int(cfg.sample_size)}"
                    )
                ]
            hits = sum(1 for v in values if det.extract(v))
            ratio = hits / len(values) if values else 0.0
            selected = forced or (hits > 0 and ratio >= cfg.min_hit_ratio)
            if hits or forced:
                reports.append(ColumnReport(table, name, forced, len(values), hits, selected))
    return reports


def scan_refs(dest: Engine, det: Detector, reports: list[ColumnReport]) -> None:
    """Extract every reference from the selected columns into the `_image_refs` table."""
    insp = inspect(dest)
    with dest.begin() as c:
        c.exec_driver_sql("DROP TABLE IF EXISTS _image_refs")
        c.exec_driver_sql(
            "CREATE TABLE _image_refs (id INTEGER PRIMARY KEY, table_name TEXT, column_name TEXT, "
            "src_rowid INTEGER, row_pk TEXT, raw_ref TEXT, position INTEGER, job_key TEXT)"
        )
    for rep in (r for r in reports if r.selected):
        pk_cols = insp.get_pk_constraint(rep.table)["constrained_columns"]
        select_list = ", ".join(["rowid"] + [q(p) for p in pk_cols] + [q(rep.column)])
        with dest.connect() as c:
            rows = c.exec_driver_sql(
                f"SELECT {select_list} FROM {q(rep.table)} WHERE {q(rep.column)} IS NOT NULL AND {q(rep.column)} != ''"
            ).fetchall()
        out = []
        seen = set()
        rows_with_refs = 0
        for row in rows:
            refs = det.extract(row[-1])
            rows_with_refs += bool(refs)
            pk = json.dumps(list(row[1:-1]), default=str)
            for pos, ref in enumerate(refs):
                out.append((rep.table, rep.column, row[0], pk, ref, pos))
                seen.add(ref)
        rep.refs, rep.distinct = len(out), len(seen)
        if out:
            with dest.begin() as c:
                c.exec_driver_sql(
                    "INSERT INTO _image_refs (table_name, column_name, src_rowid, row_pk, raw_ref, position) "
                    "VALUES (?, ?, ?, ?, ?, ?)",
                    out,
                )
